"""
RAG: summary of the search results with an LLM (Groq API).

Two generators:
* BaselineRAGGenerator: the one given with the project template, kept unchanged so we can compare.
* RAGGenerator: our improved version (Part 4). The three improvements are:
    1. Rich product context: brand, price, discount, rating, stock, category, main product details and
       a piece of the description, instead of only PID + title. The baseline prompt asks the model to
       explain the choice with price and quality, but never gives it the price or the rating.
    2. Query constraints and "no good products": price / rating limits are read from the query
       (constraints.py), checked in Python on ALL the matching products (not only the top 20), and when
       no product fits we answer without calling the LLM, saying which limit failed and what is closest.
    3. Structured, grounded answer: a system prompt with explicit rules, low temperature and a JSON
       answer that points to products by number. We check every number against the list we sent, so
       the page can only show a product that was really retrieved, with a link to its details page.
"""
import json
import os
import re
import time
from collections import OrderedDict
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from dotenv import load_dotenv

from myapp.generation.constraints import QueryConstraints, parse_constraints

load_dotenv()  # take environment variables from .env

DEFAULT_MODEL = "llama-3.1-8b-instant"
DEFAULT_ANSWER = "RAG is not available. Check your credentials (.env file) or account limits."


def _make_client():
    #imported here so the rest of the app (and the tests) work without the groq package
    from groq import Groq
    return Groq(api_key=os.environ.get("GROQ_API_KEY"))


class BaselineRAGGenerator:
    """The RAG of the project template, unchanged except that it remembers the token usage of the last call."""

    PROMPT_TEMPLATE = """
        You are an expert product advisor helping users choose the best option from retrieved e-commerce products.

        ## Instructions:
        1. Identify the single best product that matches the user's request.
        2. Present the recommendation clearly in this format:
        - Best Product: [Product PID] [Product Name]
        - Why: [Explain in plain language why this product is the best fit, referring to specific attributes like price, features, quality, or fit to user’s needs.]
        3. If there is another product that could also work, mention it briefly as an alternative.
        4. If no product is a good fit, return ONLY this exact phrase:
        "There are no good products that fit the request based on the retrieved results."

        ## Retrieved Products:
        {retrieved_results}

        ## User Request:
        {user_query}

        ## Output Format:
        - Best Product: ...
        - Why: ...
        - Alternative (optional): ...
    """

    def __init__(self, client=None):
        self.client = client
        self.last_usage = None

    def generate_response(self, user_query: str, retrieved_results: list, top_N: int = 20, **kwargs) -> str:
        """
        Generate a response using the retrieved search results.
        Returns:
            str: the text generated by the LLM
        """
        try:
            client = self.client or _make_client()
            model_name = os.environ.get("GROQ_MODEL", DEFAULT_MODEL)

            # Format the retrieved results for the prompt
            formatted_results = "\n".join(
                [f"- PID: {res.pid}, Title: {res.title}" for res in retrieved_results[:top_N]]
            )

            prompt = self.PROMPT_TEMPLATE.format(
                retrieved_results=formatted_results,
                user_query=user_query
            )

            chat_completion = client.chat.completions.create(
                messages=[
                    {
                        "role": "user",
                        "content": prompt,
                    }
                ],
                model=model_name,
            )
            self.last_usage = getattr(chat_completion, "usage", None)

            generation = chat_completion.choices[0].message.content
            return generation
        except Exception as e:
            print(f"Error during RAG generation: {e}")
            return DEFAULT_ANSWER


