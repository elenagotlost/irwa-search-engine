#product details shown first (the most useful to choose); other keys follow if there is room
DETAIL_PRIORITY = ["Fabric", "Color", "Fit", "Pattern", "Sleeve", "Neck", "Ideal For", "Type", "Occasion",
                   "Closure", "Pack of", "Outer Material", "Sole Material", "Length", "Hooded", "Size"]
#keys that don't help to choose a product
DETAIL_SKIP = {"style code", "other details", "wash care", "fabric care", "model name", "series",
               "net quantity", "generic name", "manufacturer", "packer", "importer"}
MAX_DETAILS = 8
MAX_DETAIL_VALUE = 60
MAX_DESCRIPTION = 250

SYSTEM_PROMPT = """You are a shopping assistant for an Indian fashion e-commerce website (prices in Indian rupees, Rs.).
You choose products ONLY from the numbered list you are given.

Rules:
1. Refer to products only by their number [n] from the list. Never invent products.
2. Use only the facts written in the product data. Do not invent prices, ratings, materials or features;
   if something is not in the data, do not mention it.
3. Every listed product is in stock and already meets the user's price and rating limits.
4. Choose the product that best matches what the user asked for: type of product, gender, colour,
   material, style. Use price, discount and rating to decide between products that match equally well.
   If the user prefers low prices or high ratings, give that more weight.
5. If no product in the list is really what the user asked for (for example the wrong type of product
   or the wrong gender), do not force a choice: set "best" to null and explain why in "no_match_reason".
6. Each explanation is 1-2 short sentences and cites the concrete facts that support it (price, rating,
   fabric, ...). The alternative must be a different product and say how it differs from the best one.

Answer with a JSON object only, with exactly this shape:
{"best": {"ref": <number>, "why": "<explanation>"} or null,
 "alternative": {"ref": <number>, "why": "<explanation>"} or null,
 "no_match_reason": "<only when best is null, otherwise empty>"}"""


@dataclass
class Pick:
    """A product chosen by the LLM, already checked against the list we sent."""
    ref: int
    pid: str
    title: str
    why: str
    url: str
    price: Optional[float] = None
    rating: Optional[float] = None


@dataclass
class RAGResponse:
    """
    Answer of the improved RAG, ready for the results page.
    status: "ok" (LLM picked a product), "no_match" (no product fits; LLM or our checks said so),
            "no_results" (the search found nothing), "unparsed" (LLM answer was not valid JSON, shown as text),
            "unavailable" (no API key or the API failed)
    """
    status: str
    message: str = ""
    best: Optional[Pick] = None
    alternative: Optional[Pick] = None
    overview: str = ""
    constraints: str = ""
    used_llm: bool = False
    cached: bool = False
    n_context: int = 0
    prompt_tokens: Optional[int] = None
    latency: float = 0.0
    skipped: Dict[str, int] = field(default_factory=dict)

    @property
    def text(self):
        """Plain-text version (logs, comparison script)."""
        lines = []
        if self.best:
            lines.append(f"- Best Product: [{self.best.ref}] {self.best.pid} {self.best.title}")
            lines.append(f"- Why: {self.best.why}")
            if self.alternative:
                lines.append(f"- Alternative: [{self.alternative.ref}] {self.alternative.pid} {self.alternative.title}"
                             f" - {self.alternative.why}")
        if self.message:
            lines.append(self.message)
        if self.overview:
            lines.append(f"({self.overview})")
        return "\n".join(lines)

    def __str__(self):
        return self.text


def _get(obj, name):
    return getattr(obj, name, None)


def _money(value):
    return f"Rs. {value:,.0f}"


class RAGGenerator:
    """
    Improved RAG. Usage from the web app:
        rag = RAGGenerator(corpus)                       #corpus: pid -> Document (all the fields)
        response = rag.generate_response(query, results.items)
    """

    def __init__(self, corpus: Optional[Dict[str, Any]] = None, client=None, model: Optional[str] = None,
                 top_n: int = 10, temperature: float = 0.2, cache_size: int = 256):
        """
        :param corpus: pid -> Document, to read the fields the result items don't have (details, category...)
        :param client: object with chat.completions.create (Groq client); created from .env when None
        :param top_n: products sent to the LLM. 10 with full data is about the same size as 20 bare titles
        :param temperature: low so the same query gives (almost) the same answer
        """
        self.corpus = corpus or {}
        self.client = client
        self.model = model or os.environ.get("GROQ_MODEL", DEFAULT_MODEL)
        self.top_n = top_n
        self.temperature = temperature
        self.cache = OrderedDict()
        self.cache_size = cache_size

    # --- 2. constraints and candidate selection ---------------------------------------------------

    def _doc(self, item):
        """Full document of a result item (falls back to the item itself)."""
        return self.corpus.get(_get(item, "pid"), item)

    def select_candidates(self, retrieved_results: list, constraints: QueryConstraints, top_n: int):
        """
        Walk ALL the retrieved products in ranking order and keep the ones that are in stock and fit the
        limits of the query. With a cheap / top-rated preference, the first 3*top_n that fit are re-sorted
        by price / rating, so relevance still decides which products are considered.
        :return: (list of (item, doc) to send, number of products that fit, dict with skip counts)
        """
        fitting = []
        skipped = {"price": 0, "rating": 0, "out_of_stock": 0}
        for item in retrieved_results:
            doc = self._doc(item)
            broken = constraints.check(_get(doc, "selling_price"), _get(doc, "average_rating"))
            if broken:
                for reason in set(broken):
                    skipped[reason] += 1
                continue
            if _get(doc, "out_of_stock"):
                skipped["out_of_stock"] += 1
                continue
            fitting.append((item, doc))

        pool = fitting[:3 * top_n]
        if constraints.prefer_cheap:
            pool.sort(key=lambda x: _get(x[1], "selling_price") if _get(x[1], "selling_price") is not None else float("inf"))
        elif constraints.prefer_rating:
            pool.sort(key=lambda x: -(_get(x[1], "average_rating") or 0))
        return pool[:top_n], fitting, skipped

    def explain_no_match(self, retrieved_results, constraints, skipped):
        """Deterministic answer when no product fits: which limit failed and the closest product."""
        n = len(retrieved_results)
        parts = [f"None of the {n:,} products that match your words fits"]
        if constraints.has_hard_limits:
            parts[0] += f" {constraints.describe()}"
        if not constraints.has_hard_limits or (skipped["out_of_stock"] and not skipped["price"] and not skipped["rating"]):
            parts[0] = f"All {n:,} products that match your request are out of stock"

        #closest product for the first limit the user gave (in stock if possible)
        docs = [self._doc(item) for item in retrieved_results]
        docs = [d for d in docs if not _get(d, "out_of_stock")] or docs
        closest, note = None, ""
        if constraints.max_price is not None:
            priced = [d for d in docs if _get(d, "selling_price") is not None]
            if priced:
                closest = min(priced, key=lambda d: d.selling_price)
                note = f"the cheapest is {_money(closest.selling_price)}"
        elif constraints.min_price is not None:
            priced = [d for d in docs if _get(d, "selling_price") is not None]
            if priced:
                closest = max(priced, key=lambda d: d.selling_price)
                note = f"the most expensive is {_money(closest.selling_price)}"
        elif constraints.min_rating is not None:
            rated = [d for d in docs if _get(d, "average_rating") is not None]
            if rated:
                closest = max(rated, key=lambda d: d.average_rating)
                note = f"the best rated has {closest.average_rating:.1f}"
        message = parts[0] + "."
        if closest is not None:
            message += f" Closest option: {closest.title} ({closest.pid}) - {note}."
        if constraints.has_hard_limits:
            message += " Try relaxing the limit."
        return message

    @staticmethod
    def overview(fitting, n_all, constraints):
        """One line about the whole result set, computed in Python (no LLM numbers to trust)."""
        prices = [_get(d, "selling_price") for _, d in fitting if _get(d, "selling_price") is not None]
        ratings = [_get(d, "average_rating") for _, d in fitting if _get(d, "average_rating") is not None]
        if constraints.has_hard_limits:
            text = f"{len(fitting):,} of {n_all:,} matching products are in stock and fit {constraints.describe()}"
        else:
            text = f"{len(fitting):,} of {n_all:,} matching products are in stock"
        if prices:
            text += f"; prices {_money(min(prices))}–{_money(max(prices))}"
        if ratings:
            good = sum(r >= 4 for r in ratings)
            text += f"; {good:,} rated 4+"
        return text

    # --- 1. rich context --------------------------------------------------------------------------

    @staticmethod
    def format_details(details):
        if not isinstance(details, dict):
            return ""
        keys = [k for k in DETAIL_PRIORITY if k in details]
        keys += [k for k in details if k not in keys]
        parts = []
        for key in keys:
            value = details.get(key)
            if value is None or str(key).strip().lower() in DETAIL_SKIP:
                continue
            value = re.sub(r"\s+", " ", str(value)).strip()
            if not value or value.lower() in {"na", "n/a", "no"} or len(value) > MAX_DETAIL_VALUE:
                continue
            parts.append(f"{key}: {value}")
            if len(parts) == MAX_DETAILS:
                break
        return "; ".join(parts)

    def format_product(self, ref, item, doc):
        """Text block of one product for the prompt."""
        lines = [f"[{ref}] {_get(doc, 'title') or _get(item, 'title')}"]
        brand = _get(doc, "brand")
        category = " > ".join(x for x in (_get(doc, "category"), _get(doc, "sub_category")) if x)
        meta = " | ".join(x for x in (f"Brand: {brand}" if brand else "", f"Category: {category}" if category else "") if x)
        if meta:
            lines.append(meta)
        price, actual, discount = _get(doc, "selling_price"), _get(doc, "actual_price"), _get(doc, "discount")
        if price is not None:
            price_text = f"Price: {_money(price)}"
            if actual and actual > price:
                price_text += f" (list price {_money(actual)}"
                price_text += f", {discount:.0f}% off)" if discount else ")"
            lines.append(price_text)
        rating = _get(doc, "average_rating")
        lines.append(f"Rating: {rating:.1f}/5" if rating is not None else "Rating: not rated yet")
        details = self.format_details(_get(doc, "product_details"))
        if details:
            lines.append(f"Details: {details}")
        description = re.sub(r"\s+", " ", _get(doc, "description") or "").strip()
        if description:
            if len(description) > MAX_DESCRIPTION:
                description = description[:MAX_DESCRIPTION].rsplit(" ", 1)[0] + "..."
            lines.append(f"Description: {description}")
        return "\n".join(lines)

    def build_messages(self, user_query, constraints, candidates):
        products = "\n\n".join(self.format_product(i, item, doc) for i, (item, doc) in enumerate(candidates, start=1))
        limits = constraints.describe() or "none"
        order = "best search matches first"
        if constraints.prefer_cheap:
            order = "good search matches, cheapest first"
        elif constraints.prefer_rating:
            order = "good search matches, best rated first"
        user = (f'User request: "{user_query}"\n'
                f"Limits and preferences understood from the request: {limits}\n\n"
                f"Products ({order}):\n\n{products}")
        return [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": user}]

    # --- 3. structured, grounded answer -----------------------------------------------------------

    @staticmethod
    def parse_json(text):
        """The JSON object of the answer; tolerates ```json fences or text around it."""
        if not text:
            return None
        match = re.search(r"\{.*\}", text, re.S)
        if not match:
            return None
        try:
            data = json.loads(match.group(0))
        except json.JSONDecodeError:
            return None
        return data if isinstance(data, dict) else None

    @staticmethod
    def _pick(raw, candidates):
        """A Pick if raw has a valid ref (1..len(candidates)), else None: the model can't point outside the list."""
        if not isinstance(raw, dict):
            return None
        try:
            ref = int(raw.get("ref"))
        except (TypeError, ValueError):
            return None
        if not 1 <= ref <= len(candidates):
            return None
        item, doc = candidates[ref - 1]
        return Pick(ref=ref, pid=_get(item, "pid"), title=_get(doc, "title") or _get(item, "title"),
                    why=str(raw.get("why") or "").strip(), url=_get(item, "url") or f"doc_details?pid={_get(item, 'pid')}",
                    price=_get(doc, "selling_price"), rating=_get(doc, "average_rating"))

    def call_llm(self, messages):
        client = self.client or _make_client()
        if self.client is None:
            self.client = client
        kwargs = dict(model=self.model, messages=messages, temperature=self.temperature, max_tokens=400)
        try:
            completion = client.chat.completions.create(response_format={"type": "json_object"}, **kwargs)
        except Exception as e:
            #some models / API versions reject JSON mode: try once more without it, the prompt still asks for JSON
            if "response_format" not in str(e) and "json" not in str(e).lower():
                raise
            completion = client.chat.completions.create(**kwargs)
        usage = getattr(completion, "usage", None)
        return completion.choices[0].message.content, getattr(usage, "prompt_tokens", None)

    # --- main entry point -------------------------------------------------------------------------

    def generate_response(self, user_query: str, retrieved_results: list, top_N: Optional[int] = None,
                          constraints: Optional[QueryConstraints] = None) -> RAGResponse:
        """
        :param user_query: query as written by the user
        :param retrieved_results: ALL the ranked results (ResultItem / Document), best first
        :param top_N: products sent to the LLM (default self.top_n)
        :param constraints: already parsed constraints (the web app parses them for the search); parsed here if None
        :return: RAGResponse
        """
        start = time.perf_counter()
        top_n = top_N or self.top_n
        constraints = constraints or parse_constraints(user_query)

        if not retrieved_results:
            return RAGResponse(status="no_results", constraints=constraints.describe(),
                               message="The search found no products for this request, so there is nothing to recommend.")

        candidates, fitting, skipped = self.select_candidates(retrieved_results, constraints, top_n)
        overview = self.overview(fitting, len(retrieved_results), constraints)

        if not candidates:
            return RAGResponse(status="no_match", constraints=constraints.describe(), skipped=skipped,
                               message=self.explain_no_match(retrieved_results, constraints, skipped),
                               latency=time.perf_counter() - start)

        key = (user_query.strip().lower(), tuple(_get(item, "pid") for item, _ in candidates))
        if key in self.cache:
            self.cache.move_to_end(key)
            cached = self.cache[key]
            return RAGResponse(**{**cached.__dict__, "cached": True, "latency": time.perf_counter() - start})

        response = RAGResponse(status="ok", overview=overview, constraints=constraints.describe(),
                               used_llm=True, n_context=len(candidates), skipped=skipped)
        try:
            raw, response.prompt_tokens = self.call_llm(self.build_messages(user_query, constraints, candidates))
        except Exception as e:
            print(f"Error during RAG generation: {e}")
            response.status, response.message, response.used_llm = "unavailable", DEFAULT_ANSWER, False
            response.latency = time.perf_counter() - start
            return response  #not cached: the next search tries again

        data = self.parse_json(raw)
        if data is None:
            response.status, response.message = "unparsed", (raw or "").strip()
        else:
            response.best = self._pick(data.get("best"), candidates)
            response.alternative = self._pick(data.get("alternative"), candidates)
            if response.alternative and response.best and response.alternative.ref == response.best.ref:
                response.alternative = None
            if response.best is None:
                if response.alternative:
                    #the model only gave a valid alternative: promote it rather than show nothing
                    response.best, response.alternative = response.alternative, None
                else:
                    response.status = "no_match"
                    response.message = (str(data.get("no_match_reason") or "").strip()
                                        or "There are no good products that fit the request based on the retrieved results.")

        response.latency = time.perf_counter() - start
        self.cache[key] = response
        if len(self.cache) > self.cache_size:
            self.cache.popitem(last=False)
        return response
